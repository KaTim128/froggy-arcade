/** Everything on screen for the current phase, thrown away between phases. */
function newLayer(): Phaser.GameObjects.Container {
  layer?.destroy(true);
  for (const b of armBtns) b.destroy();
  armBtns = [];
  layer = S().add.container(0, 0);
  boxes = [];
  panelText = [];
  return layer;
}

