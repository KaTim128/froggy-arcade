/**
 * Where each part sits on the body, in the monster's own pixels with the feet
 * at the origin.  It is one table, and both the assembly screen and the arena
 * draw from it, so a part cannot be attached in one place and floating in the
 * other.  Nothing here overlaps anything else by more than the two pixels that
 * make a joint.
 */
const ANCHOR: Record<Slot, { x: number; y: number; w: number; h: number }> = {
  legL: { x: -7, y: -8, w: 10, h: 16 },
  legR: { x: 7, y: -8, w: 10, h: 16 },
  body: { x: 0, y: -27, w: 26, h: 22 },
  armL: { x: -17, y: -28, w: 9, h: 17 },
  armR: { x: 17, y: -28, w: 9, h: 17 },
  head: { x: 0, y: -45, w: 24, h: 19 },
};
/** How tall an assembled Frogster is, feet to crown. */
export const MONSTER_H = 54;

/** A couple of marks that say which element a part is made of. */
function detail(
  scene: Phaser.Scene,
  c: Phaser.GameObjects.Container,
  el: Element,
  x: number,
  y: number,
  w: number,
  h: number,
): void {
  const put = (dx: number, dy: number, sw: number, sh: number, col: number, ang = 0): void => {
    c.add(scene.add.rectangle(x + dx, y + dy, sw, sh, col).setAngle(ang));
  };
  const dot = (dx: number, dy: number, r: number, col: number): void => {
    c.add(scene.add.circle(x + dx, y + dy, r, col));
  };
  const q = Math.max(3, Math.min(w, h) / 3);
  switch (el) {
    case 'fire':
      put(-w / 5, -h / 4, q * 0.7, q, PALETTE.ember, 18);
      put(w / 5, -h / 3, q * 0.5, q * 0.8, PALETTE.gold, -14);
      put(0, h / 4, w * 0.5, 1, PALETTE.gold);
      break;
    case 'water':
      dot(-w / 5, -h / 5, q * 0.35, PALETTE.white);
      dot(w / 4, h / 6, q * 0.25, PALETTE.white);
      put(0, -h / 3, w * 0.55, 1, 0x9fd8ff);
      break;
    case 'grass':
      put(-w / 4, -h / 5, q * 0.9, q * 0.45, 0x9ad97a, 28);
      put(w / 4, h / 6, q * 0.8, q * 0.4, 0x9ad97a, -24);
      put(0, 0, 1, h * 0.5, 0x2f5c33);
      break;
    case 'electric':
      put(-w / 6, -h / 5, q * 0.8, 1.4, PALETTE.cream, 34);
      put(w / 8, h / 8, q * 0.7, 1.4, PALETTE.cream, -40);
      dot(w / 3, -h / 3, 1, PALETTE.white);
      break;
    case 'steel':
      put(0, -h / 4, w * 0.75, 1.4, PALETTE.bone);
      put(0, h / 5, w * 0.75, 1.4, PALETTE.bone);
      dot(-w / 3, h / 5, 1.1, PALETTE.fog);
      dot(w / 3, h / 5, 1.1, PALETTE.fog);
      break;
    default:
      put(-w / 5, h / 6, q * 0.8, q * 0.6, 0x7a5a38);
      put(w / 4, -h / 5, q * 0.6, q * 0.5, 0xc59a63, 16);
      dot(0, 0, 1.2, 0xd7c7a0);
      break;
  }
}

/**
 * One Frogster, out of whatever parts it has so far.
 *
 * Rebuilt from scratch every time a part is added, which is why a half-built
 * monster cannot end up with a leg drawn over its own head: the container is
 * emptied and filled back to front, legs first and the head last, every time.
 * `dir` is -1 for the one on the right of the arena, so both face the middle.
 */
function drawMonster(
  scene: Phaser.Scene,
  c: Phaser.GameObjects.Container,
  parts: Partial<Record<Slot, Part>>,
  dir = 1,
): void {
  c.removeAll(true);
  const piece = (slot: Slot): void => {
    const p = parts[slot];
    if (!p) return;
    const a = ANCHOR[slot];
    const x = a.x * dir;
    // A DARK EDGE ON EVERY PIECE.  Without it an arm and a torso of the same
    // element merge into one orange slab and the monster stops reading as
    // something that was ASSEMBLED, which is the whole of what it is.
    const body = scene.add.rectangle(x, a.y, a.w, a.h, EL_COLOUR[p.el]);
    body.setStrokeStyle(1, PALETTE.black, 0.55);
    c.add(body);
    c.add(scene.add.rectangle(x, a.y + a.h / 2 - 1.5, a.w - 2, 2, EL_DARK[p.el]));
    detail(scene, c, p.el, x, a.y, a.w, a.h);
  };
  // Back to front: what is behind the torso goes down first.
  piece('legL');
  piece('legR');
  piece('armL');
  piece('armR');
  piece('body');
  const h = parts.head;
  if (h) {
    piece('head');
    // AND IT IS STILL A FROG.  Two eye bumps up on top with a pupil in each,
    // and a wide mouth under them: the one thing that must survive whatever
    // six elements got bolted together.
    const a = ANCHOR.head;
    for (const s of [-1, 1]) {
      c.add(scene.add.circle(s * 7 * dir, a.y - a.h / 2 + 1, 4.5, EL_COLOUR[h.el]));
      c.add(scene.add.circle(s * 7 * dir, a.y - a.h / 2 + 1, 3, PALETTE.cream));
      c.add(scene.add.circle(s * 7 * dir + dir, a.y - a.h / 2 + 1, 1.4, PALETTE.black));
    }
    c.add(scene.add.rectangle(0, a.y + 4, 13, 2, PALETTE.black).setAlpha(0.65));
  }
}


