/**
 * FROGSTER MASH.  Fifteen tokens in, thirty out.
 *
 * A creature-builder with a fight on the end of it.  The player assembles a
 * Frogster out of six parts taken off a conveyor belt -- two legs, two arms,
 * a body and a head, in that order -- and then it fights one the machine built
 * the same way, out of the same parts, under the same rules.
 *
 * THE WHOLE GAME IS THE SIX CHOICES.  The fight is turn-based and short and
 * has exactly two buttons in it, because everything that decides it was
 * decided on the belt: which elements you took, what they are strong and weak
 * against, and whether you took enough of one to earn the synergy.  A player
 * who reads the cards wins; a player who grabs the biggest number does not,
 * because the biggest number is an element the enemy happens to resist.
 *
 * THE ARITHMETIC IS IN ONE PLACE.  `statsOf` turns a part into four numbers,
 * `assemble` turns six parts into a monster, and `damage` is the only thing
 * that takes health off anybody.  The enemy is generated by the same two
 * functions the player's belt uses, so there is no second set of rules for it
 * to be unfair with.
 *
 * NOTHING IN HERE TOUCHES THE LEDGER.  The shell charged the fifteen when the
 * player pressed PLAY on the how-to card and it pays the thirty on `api.win`,
 * once, guarded by its own latch -- this file only ever says which of the two
 * happened, and says it exactly once (`ended`).
 */

