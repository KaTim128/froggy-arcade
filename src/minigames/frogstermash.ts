export const frogsterMash: MinigameModule = {
  id: ID,
  title: 'FROGSTER MASH',
  music: 'game_frogstermash',
  rules: 'build a frogster out of six parts, then fight with it',
  tutorial: {
    objective: [
      'PICK SIX PARTS OFF THE BELT: LEGS, ARMS, ARMOR, HEAD.',
      'EACH PART HAS AN ELEMENT. ELEMENTS BEAT ELEMENTS.',
      'THEN FIGHT. EMPTY THE CHALLENGER AND TAKE THE 30.',
    ],
    controls: [
      ['LEFT/RIGHT', 'INSPECT THE BOXES'],
      ['SPACE', 'TAKE THE LIT BOX'],
      ['CLICK', 'INSPECT, THEN CLICK AGAIN TO TAKE'],
      ['1 / 2', 'SWING LEFT OR RIGHT ARM'],
    ],
  },
  touch: {
    stick: 'lr',
    arrows: true,
    buttons: [
      { label: 'TAKE', key: 'SPACE', primary: true },
      { label: 'L', key: 'ONE' },
      { label: 'R', key: 'TWO' },
    ],
  },

  create(scene: Phaser.Scene, api: MinigameApi) {
    scene0 = scene;
    apiRef = api;
    layer = null;
    reset();

    const kb = scene.input.keyboard;
    kb?.on('keydown-LEFT', () => {
      if (phase === 'pick') highlight((hi + offer.length - 1) % offer.length);
    });
    kb?.on('keydown-RIGHT', () => {
      if (phase === 'pick') highlight((hi + 1) % offer.length);
    });
    kb?.on('keydown-A', () => {
      if (phase === 'pick') highlight((hi + offer.length - 1) % offer.length);
    });
    kb?.on('keydown-D', () => {
      if (phase === 'pick') highlight((hi + 1) % offer.length);
    });
    kb?.on('keydown-SPACE', () => {
      if (phase === 'pick') take(hi);
    });
    kb?.on('keydown-ENTER', () => {
      if (phase === 'pick') take(hi);
    });
    kb?.on('keydown-ONE', () => {
      if (phase === 'battle') swing('armL');
    });
    kb?.on('keydown-TWO', () => {
      if (phase === 'battle') swing('armR');
    });

    showTitle();

    if (import.meta.env?.DEV) {
      (window as unknown as Record<string, unknown>).__mash = {
        state: () => ({
          phase,
          stage,
          slot: ORDER[stage],
          hi,
          pickT: Math.round(pickT),
          ended,
          turn,
          busy,
          offer: offer.map((p) => ({ el: p.el, power: p.power, atk: +p.atk.toFixed(3), def: +p.def.toFixed(3), spd: +p.spd.toFixed(3), hp: +p.hp.toFixed(3) })),
          picked: ORDER.filter((s) => picked[s]).map((s) => ({ slot: s, el: picked[s]!.el, power: picked[s]!.power })),
          player: player && { atk: +player.atk.toFixed(3), def: +player.def.toFixed(3), spd: +player.spd.toFixed(3), hp: player.hp, maxHp: player.maxHp, synergy: player.synergy },
          enemy: enemy && { atk: +enemy.atk.toFixed(3), def: +enemy.def.toFixed(3), spd: +enemy.spd.toFixed(3), hp: enemy.hp, maxHp: enemy.maxHp, synergy: enemy.synergy },
          log: logText?.text ?? '',
        }),
        /** Where the five boxes are, so a harness can see the belt moving. */
        belt: () => boxes.map((b) => Math.round(b.x)),
        highlight: (i: number) => highlight(i),
        take: (i: number) => take(i),
        /** Take a box of a named element at this stage, if one is on offer. */
        takeEl: (el: Element) => {
          const i = offer.findIndex((p) => p.el === el);
          if (i >= 0) take(i);
          return i >= 0;
        },
        swing: (arm: 'armL' | 'armR') => swing(arm),
        /** Put a monster on the ropes, to reach the end of a fight quickly. */
        setHp: (who: 'player' | 'enemy', n: number) => {
          const m = who === 'player' ? player : enemy;
          if (m) m.hp = n;
          refreshBars();
        },
        /** The rules, exposed so the arithmetic can be checked rather than watched. */
        rules: { BASE, STRONG, WEAK, POWER_MUL, effect, statsOf, assemble, damage },
      };
      scene.events.once(Phaser.Scenes.Events.SHUTDOWN, () => {
        delete (window as unknown as Record<string, unknown>).__mash;
      });
    }
  },

  update(_time: number, delta: number) {
    clock += delta;
    if (phase !== 'pick') return;
    // The belt runs whether or not anybody is looking at it.
    beltOff -= (BELT_SPEED * delta) / 1000;
    layoutBelt();
    const before = pickT;
    pickT -= delta;
    if (timerBar) timerBar.width = Math.max(0, (pickT / PICK_MS) * 240);
    // One clank per box-width of travel, which is a belt and not a drone.
    if (Math.floor(-beltOff / 14) !== Math.floor((-beltOff + (BELT_SPEED * delta) / 1000) / 14)) {
      audio.sfx('wheel_tick', 0.12);
    }
    if (before > 2000 && pickT <= 2000) audio.sfx('buzzer', 0.25);
    if (pickT <= 0) autoPick();
  },

  destroy() {
    const kb = scene0?.input.keyboard;
    for (const k of ['LEFT', 'RIGHT', 'A', 'D', 'SPACE', 'ENTER', 'ONE', 'TWO']) kb?.off(`keydown-${k}`);
    for (const b of armBtns) b.destroy();
    armBtns = [];
    layer?.destroy(true);
    layer = null;
    monsterC = null;
    enemyC = null;
    scene0 = null;
    apiRef = null;
    reset();
  },
};
