function showTitle(): void {
  phase = 'title';
  const c = newLayer();
  c.add(S().add.rectangle(0, 18, GAME_W, 162, 0x131a2b).setOrigin(0, 0));
  const t1 = centerText(S(), GAME_W / 2, 52, 'FROGSTER', PALETTE.gold, 24);
  const t2 = centerText(S(), GAME_W / 2, 78, 'MASH', PALETTE.neon, 24);
  c.add(t1);
  c.add(t2);
  S().tweens.add({ targets: [t1, t2], scaleX: 1.06, scaleY: 1.06, duration: 420, yoyo: true, repeat: -1 });
  c.add(centerText(S(), GAME_W / 2, 104, 'BUILD IT. THEN FIGHT WITH IT.', PALETTE.tealLight));

  // A Frogster of six random parts, bouncing, so the title screen shows the
  // thing the game is about rather than the words for it.
  const demo = S().add.container(GAME_W / 2, 168);
  const parts = {} as Record<Slot, Part>;
  for (const slot of ORDER) parts[slot] = statsOf(slot, ELEMENTS[rnd(ELEMENTS.length)], 1 + rnd(5));
  drawMonster(S(), demo, parts);
  demo.setScale(0.8);
  c.add(demo);
  S().tweens.add({ targets: demo, y: 162, duration: 380, yoyo: true, repeat: -1, ease: 'Sine.easeInOut' });

  audio.sfx('stinger', 0.5);
  S().time.delayedCall(1700, () => {
    if (phase === 'title') startStage(0);
  });
}

// ---------------------------------------------------------- assembly phase

function startStage(n: number): void {
  phase = 'pick';
  stage = n;
  const slot = ORDER[n];
  offer = offerFor(slot);
  hi = 0;
  pickT = PICK_MS;
  beltOff = 0;
  const c = newLayer();

  c.add(S().add.rectangle(0, 18, GAME_W, 162, 0x10161f).setOrigin(0, 0));
  c.add(text(S(), 6, 22, `PART ${n + 1} OF 6`, PALETTE.ash));
  c.add(centerText(S(), GAME_W / 2, 26, SLOT_NAME[slot], PALETTE.gold, 16));

  // the clock, as a bar rather than a number: a bar is read without reading
  c.add(S().add.rectangle(GAME_W / 2, 36, 240, 3, PALETTE.slate));
  timerBar = S().add.rectangle(GAME_W / 2 - 120, 36, 240, 3, PALETTE.tealLight).setOrigin(0, 0.5);
  c.add(timerBar);

  // ---- what has been bolted on so far, in its own column on the left, with
  // nothing else allowed into it: the panel starts at 70 and the monster is
  // never wider than 34, so no stat line can ever cross the thing it describes.
  c.add(centerText(S(), 34, 46, 'YOURS', PALETTE.ash));
  monsterC = S().add.container(34, 126);
  monsterC.setScale(0.62);
  drawMonster(S(), monsterC, picked);
  c.add(monsterC);

  // ---- and the card for whichever box is lit, on the right
  const px = 70;
  const pw = GAME_W - px - 5;
  c.add(S().add.rectangle(px, 42, pw, 84, PALETTE.ink).setOrigin(0, 0).setStrokeStyle(1, PALETTE.steel));
  panelChip = S().add.rectangle(px + 5, 47, 9, 9, PALETTE.slate).setOrigin(0, 0);
  c.add(panelChip);
  for (let i = 0; i < 7; i++) {
    const t = text(S(), px + (i === 0 ? 18 : 5), 47 + i * 11, '', PALETTE.cream);
    panelText.push(t);
    c.add(t);
  }

  // ---- the belt, and the five boxes riding it
  c.add(S().add.rectangle(0, BELT_Y + BOX_H / 2 + 2, GAME_W, 7, PALETTE.steel).setOrigin(0, 0));
  for (let i = 0; i < 5; i++) {
    const box = S().add.container(0, BELT_Y);
    const part = offer[i];
    box.add(S().add.rectangle(0, 0, BOX_W, BOX_H, PALETTE.ink).setStrokeStyle(1, PALETTE.steel));
    box.add(S().add.rectangle(0, -BOX_H / 2 + 5, BOX_W - 4, 8, EL_DARK[part.el]));
    box.add(centerText(S(), 0, -BOX_H / 2 + 5, part.el.toUpperCase(), PALETTE.cream));
    box.add(S().add.rectangle(0, 2, 18, 12, EL_COLOUR[part.el]));
    box.add(centerText(S(), 0, BOX_H / 2 - 6, `PWR ${part.power}`, PALETTE.gold));
    box.setSize(BOX_W, BOX_H).setInteractive({ useHandCursor: true });
    box.on('pointerdown', () => {
      if (phase !== 'pick') return;
      if (hi === i) take(i);
      else highlight(i);
    });
    boxes.push(box);
    c.add(box);
  }
  c.add(centerText(S(), GAME_W / 2, 173, '[<-] [->] INSPECT   [SPACE] TAKE', PALETTE.ash));
  layoutBelt();
  highlight(0, true);
}

function layoutBelt(): void {
  boxes.forEach((b, i) => {
    b.x = (((i * BOX_GAP + beltOff) % BELT_SPAN) + BELT_SPAN) % BELT_SPAN;
  });
}

function highlight(i: number, quiet = false): void {
  hi = i;
  boxes.forEach((b, k) => {
    const frame = b.list[0] as Phaser.GameObjects.Rectangle;
    frame.setStrokeStyle(k === i ? 2 : 1, k === i ? PALETTE.gold : PALETTE.steel);
    b.setScale(k === i ? 1.06 : 1);
  });
  if (!quiet) audio.sfx('ui_hover', 0.4);
  showCard(offer[i]);
}

/** The highlighted part, spelled out: every number a choice could turn on. */
