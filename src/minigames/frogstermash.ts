function take(i: number): void {
  if (phase !== 'pick') return;
  const part = offer[i];
  if (!part) return;
  picked[part.slot] = part;
  audio.sfx('ui_blip', 0.6);
  audio.sfx('item_thud', 0.5);
  if (monsterC) drawMonster(S(), monsterC, picked);
  if (stage + 1 < ORDER.length) {
    S().time.delayedCall(240, () => startStage(stage + 1));
    phase = 'title'; // a holding state: nothing reads the belt while it swaps
  } else {
    S().time.delayedCall(260, showSummary);
    phase = 'title';
  }
}

/** The clock ran out: take what is lit, or a box at random if nothing is. */
function autoPick(): void {
  take(hi >= 0 && hi < offer.length ? hi : rnd(offer.length));
}

