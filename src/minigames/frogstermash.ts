// ===================================================================== rules

export type Element = 'fire' | 'water' | 'grass' | 'electric' | 'steel' | 'ground';
export type Slot = 'legL' | 'legR' | 'armL' | 'armR' | 'body' | 'head';

/** The order the six parts are chosen in, and the order they are named in. */
const ORDER: Slot[] = ['legL', 'legR', 'armL', 'armR', 'body', 'head'];
const SLOT_NAME: Record<Slot, string> = {
  legL: 'LEFT LEG',
  legR: 'RIGHT LEG',
  armL: 'LEFT ARM',
  armR: 'RIGHT ARM',
  body: 'BODY ARMOR',
  head: 'HEAD',
};

/** Every element's four numbers, on the one-to-five scale the cards show. */
const BASE: Record<Element, { atk: number; def: number; spd: number; hp: number }> = {
  fire: { atk: 5, def: 2, spd: 4, hp: 3 },
  water: { atk: 3, def: 4, spd: 3, hp: 4 },
  grass: { atk: 3, def: 3, spd: 3, hp: 5 },
  electric: { atk: 4, def: 2, spd: 5, hp: 2 },
  steel: { atk: 2, def: 5, spd: 1, hp: 5 },
  ground: { atk: 4, def: 4, spd: 2, hp: 4 },
};
const ELEMENTS = Object.keys(BASE) as Element[];

/** What each element beats.  `WEAK[a]` is what beats `a`, and they agree. */
const STRONG: Record<Element, Element[]> = {
  fire: ['grass', 'steel'],
  water: ['fire', 'ground'],
  grass: ['water', 'ground'],
  electric: ['water'],
  steel: ['grass'],
  ground: ['fire', 'electric', 'steel'],
};
const WEAK: Record<Element, Element[]> = {
  fire: ['water', 'ground'],
  water: ['grass', 'electric'],
  grass: ['fire', 'steel'],
  electric: ['ground'],
  steel: ['fire', 'ground'],
  ground: ['water', 'grass'],
};

const STRONG_MUL = 1.5;
const WEAK_MUL = 0.75;
/** Power Rating 1..5, as a multiplier on the part's PRIMARY attributes. */
const POWER_MUL = [0, 0.8, 0.9, 1.0, 1.1, 1.2];
/** Four of six parts sharing an element is worth a tenth, both ways. */
const SYNERGY_AT = 4;
const SYNERGY_MUL = 1.1;

/** One attack's element against one defending element. */
export function effect(att: Element, def: Element): number {
  if (STRONG[att].includes(def)) return STRONG_MUL;
  if (WEAK[att].includes(def)) return WEAK_MUL;
  return 1;
}

const EL_COLOUR: Record<Element, number> = {
  fire: 0xff7a3d,
  water: 0x46a0e0,
  grass: 0x6fbb6a,
  electric: 0xffd45e,
  steel: 0x8e9cad,
  ground: 0xa8754a,
};
const EL_DARK: Record<Element, number> = {
  fire: 0xa8451f,
  water: 0x1f5c8a,
  grass: 0x3f7a4a,
  electric: 0xc77a1b,
  steel: 0x3a4a5c,
  ground: 0x6b4a2f,
};

export interface Part {
  slot: Slot;
  el: Element;
  /** 1..5.  Shown on every card and folded into the primary attributes. */
  power: number;
  atk: number;
  def: number;
  spd: number;
  hp: number;
}

/**
 * What a part of this element at this power contributes.
 *
 * Each slot has a job and the numbers follow it: legs are speed with a little
 * attack behind them, arms are attack, the body is defence and health and
 * pays for it in speed, and the head is the smaller half of the body.  The
 * Power Rating multiplies the PRIMARY attributes only -- a power-five leg is
 * faster, not tougher.
 *
 * The armour's speed penalty comes off its own element's DEFENCE, which is
 * what makes steel both the heaviest plate in the game and the slowest,
 * without either being written down as a special case.
 */
export function statsOf(slot: Slot, el: Element, power: number): Part {
  const b = BASE[el];
  const p = POWER_MUL[power];
  const mk = (atk: number, def: number, spd: number, hp: number): Part => ({
    slot, el, power, atk, def, spd, hp,
  });
  switch (slot) {
    case 'legL':
    case 'legR':
      return mk(b.atk * 0.25 * p, b.def * 0.1, b.spd * p, b.hp * 0.3);
    case 'armL':
    case 'armR':
      return mk(b.atk * p, b.def * 0.1, b.spd * 0.1, b.hp * 0.3);
    case 'body':
      return mk(0, b.def * 1.2 * p, -(b.def * 0.35), b.hp * 1.6 * p);
    default:
      return mk(0, b.def * 0.8 * p, 0, b.hp * 1.0 * p);
  }
}

/** Health and damage are scaled off the 1-5 numbers so a fight runs ~7 hits. */
const HP_SCALE = 8;
const ATK_SCALE = 8;
/** How much total defence is worth: damage is divided by 1 + def/this. */
const DEF_SOFT = 10;

export interface Monster {
  parts: Record<Slot, Part>;
  atk: number;
  def: number;
  spd: number;
  hp: number;
  maxHp: number;
  /** The element four or more of the six parts share, if there is one. */
  synergy: Element | null;
}

export function assemble(parts: Record<Slot, Part>): Monster {
  const all = ORDER.map((s) => parts[s]);
  const sum = (f: (p: Part) => number): number => all.reduce((a, p) => a + f(p), 0);
  const count = new Map<Element, number>();
  for (const p of all) count.set(p.el, (count.get(p.el) ?? 0) + 1);
  let synergy: Element | null = null;
  for (const [el, n] of count) if (n >= SYNERGY_AT) synergy = el;
  const hp = Math.max(1, Math.round(sum((p) => p.hp) * HP_SCALE));
  return {
    parts,
    atk: sum((p) => p.atk),
    def: sum((p) => p.def),
    // The armour's penalty is already negative, so this is one sum and not a
    // sum with a subtraction hiding in it.
    spd: sum((p) => p.spd),
    hp,
    maxHp: hp,
    synergy,
  };
}

export interface Hit {
  dmg: number;
  /** 'strong' | 'weak' | 'neutral', from the defender's armour and head. */
  band: 'strong' | 'weak' | 'neutral';
  el: Element;
  synergy: boolean;
}

/**
 * One swing, and the only thing in the game that takes health off anybody.
 *
 * The arm's attack and its Power Rating make the raw number; the defender's
 * total defence divides it; the elements decide the rest.  Defence against an
 * attack is the AVERAGE of what the body armour and the head think of it, so
 * a player who plates themselves in one element is resisted or shredded
 * wholesale and a player who mixes is neither.
 *
 * `vary` is the small roll that stops a fight being arithmetic the player can
 * do in their head.  It is injectable so a test can take it out.
 */
export function damage(att: Monster, defend: Monster, arm: 'armL' | 'armR', vary = Math.random): Hit {
  const a = att.parts[arm];
  const el = a.el;
  const raw = a.atk * POWER_MUL[a.power] * ATK_SCALE;
  const eff = (effect(el, defend.parts.body.el) + effect(el, defend.parts.head.el)) / 2;

  // SYNERGY, BOTH WAYS.  The attacker's own element hits a tenth harder, and a
  // defender whose four-part element resists what is coming takes a tenth less.
  const synAtt = att.synergy === el;
  let mul = synAtt ? SYNERGY_MUL : 1;
  if (defend.synergy && STRONG[defend.synergy].includes(el)) mul /= SYNERGY_MUL;

  const roll = 0.9 + vary() * 0.2;
  const dmg = Math.max(1, Math.round((raw * eff * mul * roll) / (1 + defend.def / DEF_SOFT)));
  return {
    dmg,
    band: eff > 1.02 ? 'strong' : eff < 0.98 ? 'weak' : 'neutral',
    el,
    synergy: synAtt,
  };
}

// ================================================================ generation

const rnd = (n: number): number => Math.floor(Math.random() * n);

/**
 * Five boxes for one stage, and no two of them the same.
 *
 * "Do not place identical options in all five boxes" is the floor; this goes
 * further and makes every box a different element/power pair, so there is
 * always something to compare.  Five of six elements appear, which is what
 * makes the choice a choice.
 */
function offerFor(slot: Slot): Part[] {
  const els = [...ELEMENTS];
  for (let i = els.length - 1; i > 0; i--) {
    const j = rnd(i + 1);
    [els[i], els[j]] = [els[j], els[i]];
  }
  return els.slice(0, 5).map((el) => statsOf(slot, el, 1 + rnd(5)));
}

/**
 * The machine's own Frogster, built to land near the player's.
 *
 * It is generated the same way and then NUDGED, not scripted: parts are rolled
 * until its total health and attack sit inside a band either side of the
 * player's, so it is neither a pushover nor a wall.  It is never built to
 * counter the player's elements -- an enemy that always resists what you
 * picked would make the six choices pointless, which is the one thing this
 * game cannot afford.
 */
function buildEnemy(player: Monster): Monster {
  const score = (m: Monster): number => m.atk * 6 + m.def * 3 + m.hp / HP_SCALE + m.spd;
  const target = score(player);
  let best: Monster | null = null;
  for (let tries = 0; tries < 40; tries++) {
    const parts = {} as Record<Slot, Part>;
    for (const slot of ORDER) parts[slot] = statsOf(slot, ELEMENTS[rnd(ELEMENTS.length)], 1 + rnd(5));
    const m = assemble(parts);
    if (!best || Math.abs(score(m) - target) < Math.abs(score(best) - target)) best = m;
    // Close enough, and a shade under the player's: the machine is meant to be
    // beatable by somebody who chose well.
    if (Math.abs(score(m) - target) < target * 0.08) return m;
  }
  return best!;
}

/**
 * Which arm the machine swings.
 *
 * It works out what each of its two arms would do and takes the better one --
 * but only four times in five.  The fifth is the other arm, which is what
 * stops a player learning the pattern in one fight and playing against a
 * lookup table for the rest of them.
 */
function enemyArm(enemy: Monster, player: Monster): 'armL' | 'armR' {
  const l = effect(enemy.parts.armL.el, player.parts.body.el) * enemy.parts.armL.atk;
  const r = effect(enemy.parts.armR.el, player.parts.body.el) * enemy.parts.armR.atk;
  const best: 'armL' | 'armR' = l >= r ? 'armL' : 'armR';
  if (Math.random() < 0.2) return best === 'armL' ? 'armR' : 'armL';
  return best;
}

