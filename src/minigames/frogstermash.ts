function startBattle(): void {
  phase = 'battle';
  busy = false;
  // SPEED DECIDES WHO SWINGS FIRST, and a tie is a coin.
  turn = player!.spd > enemy!.spd ? 'player' : player!.spd < enemy!.spd ? 'enemy' : Math.random() < 0.5 ? 'player' : 'enemy';

  const c = newLayer();
  c.add(S().add.rectangle(0, 18, GAME_W, 162, 0x16202e).setOrigin(0, 0));
  c.add(S().add.rectangle(0, 122, GAME_W, 58, 0x22303f).setOrigin(0, 0));

  // ---- the two bars, and the numbers under them
  const bar = (x: number, name: string, colour: number): [Phaser.GameObjects.Rectangle, Phaser.GameObjects.BitmapText] => {
    c.add(text(S(), x, 24, name, PALETTE.ash));
    c.add(S().add.rectangle(x, 34, 130, 7, PALETTE.slate).setOrigin(0, 0));
    const fill = S().add.rectangle(x + 1, 35, 128, 5, colour).setOrigin(0, 0);
    c.add(fill);
    const num = text(S(), x + 130, 24, '', colour).setOrigin(1, 0);
    c.add(num);
    return [fill, num];
  };
  [hpBarP, hpTextP] = bar(8, 'YOURS', PALETTE.mossLight);
  [hpBarE, hpTextE] = bar(GAME_W - 138, 'CHALLENGER', PALETTE.blood);

  monsterC = S().add.container(74, 120);
  drawMonster(S(), monsterC, player!.parts);
  c.add(monsterC);
  enemyC = S().add.container(GAME_W - 74, 120);
  drawMonster(S(), enemyC, enemy!.parts, -1);
  c.add(enemyC);

  logText = centerText(S(), GAME_W / 2, 132, '', PALETTE.cream);
  c.add(logText);

  // ---- one button per arm, each wearing its own element
  (['armL', 'armR'] as const).forEach((arm, i) => {
    const p = player!.parts[arm];
    const x = i === 0 ? 84 : GAME_W - 84;
    armBtns.push(
      button(S(), x, 158, `${i === 0 ? 'L' : 'R'} ARM: ${p.el.toUpperCase()}`, () => swing(arm), {
        width: 122,
        height: 16,
        fill: EL_DARK[p.el],
        hoverFill: EL_COLOUR[p.el],
      }),
    );
    c.add(centerText(S(), x, 172, `PWR ${p.power}   ATK ${p.atk.toFixed(1)}`, PALETTE.ash));
  });

  refreshBars();
  say(turn === 'player' ? 'YOU ARE FASTER - YOU SWING FIRST' : 'IT IS FASTER - BRACE');
  if (turn === 'enemy') S().time.delayedCall(900, enemyTurn);
}

function refreshBars(): void {
  const set = (bar: Phaser.GameObjects.Rectangle | null, num: Phaser.GameObjects.BitmapText | null, m: Monster | null): void => {
    if (!bar || !num || !m) return;
    const hp = Math.max(0, m.hp);
    bar.width = Math.max(0, Math.round((hp / m.maxHp) * 128));
    num.setText(`${hp} / ${m.maxHp}`);
  };
  set(hpBarP, hpTextP, player);
  set(hpBarE, hpTextE, enemy);
}

function say(msg: string, colour: number = PALETTE.cream): void {
  logText?.setText(msg).setTint(colour);
}

/** The player's swing.  Every way in goes through here, and it is latched. */
function swing(arm: 'armL' | 'armR'): void {
  if (phase !== 'battle' || busy || turn !== 'player' || ended) return;
  busy = true;
  resolve(player!, enemy!, arm, monsterC, enemyC, 1, () => {
    if (enemy!.hp <= 0) return finishBattle(true);
    turn = 'enemy';
    S().time.delayedCall(620, enemyTurn);
  });
}

function enemyTurn(): void {
  if (phase !== 'battle' || ended) return;
  busy = true;
  const arm = enemyArm(enemy!, player!);
  resolve(enemy!, player!, arm, enemyC, monsterC, -1, () => {
    if (player!.hp <= 0) return finishBattle(false);
    turn = 'player';
    busy = false;
    say('YOUR SWING - PICK AN ARM');
  });
}

/**
 * One exchange, start to finish: the lunge, the number, the bar, the word.
 *
 * `busy` is held for the whole of it and only let go by the caller, which is
 * what stops a hammered button from queueing four swings behind one animation.
 */
function resolve(
  att: Monster,
  def: Monster,
  arm: 'armL' | 'armR',
  attC: Phaser.GameObjects.Container | null,
  defC: Phaser.GameObjects.Container | null,
  dir: number,
  done: () => void,
): void {
  const hit = damage(att, def, arm);
  const who = att === player ? 'YOU' : 'IT';
  say(`${who}: ${hit.el.toUpperCase()} STRIKE...`, EL_COLOUR[hit.el]);

  const home = attC?.x ?? 0;
  S().tweens.add({
    targets: attC,
    x: home + 22 * dir,
    duration: 150,
    yoyo: true,
    onYoyo: () => {
      def.hp = Math.max(0, def.hp - hit.dmg);
      refreshBars();
      audio.sfx(hit.band === 'strong' ? 'boom' : hit.band === 'weak' ? 'fence_thunk' : 'whack', hit.band === 'strong' ? 0.6 : 0.5);
      audio.sfx('item_thud', 0.35);
      if (defC) {
        S().tweens.add({ targets: defC, x: defC.x - 8 * dir, duration: 90, yoyo: true });
        S().cameras.main.shake(hit.band === 'strong' ? 180 : 80, hit.band === 'strong' ? 0.006 : 0.003);
      }
      const pop = centerText(S(), (defC?.x ?? 160), 84, `-${hit.dmg}`, hit.band === 'strong' ? PALETTE.gold : PALETTE.cream, 16);
      layer?.add(pop);
      S().tweens.add({ targets: pop, y: 62, alpha: 0, duration: 620, onComplete: () => pop.destroy() });
      const word =
        hit.band === 'strong' ? 'SUPER EFFECTIVE!' : hit.band === 'weak' ? 'NOT VERY EFFECTIVE' : 'A CLEAN HIT';
      say(`${who}: ${hit.el.toUpperCase()} - ${word}${hit.synergy ? ' +SYNERGY' : ''}`,
        hit.band === 'strong' ? PALETTE.gold : hit.band === 'weak' ? PALETTE.ash : PALETTE.cream);
    },
    onComplete: () => {
      if (attC) attC.x = home;
      S().time.delayedCall(360, done);
    },
  });
}

// --------------------------------------------------------------- the result

function finishBattle(won: boolean): void {
  phase = 'over';
  busy = true;
  for (const b of armBtns) b.destroy();
  armBtns = [];

  // BOTH OF THEM STEP OUT TO THE EDGES, so the card that lands between them
  // does not sit on top of the two things the whole game was about.
  const loser = won ? enemyC : monsterC;
  if (loser) S().tweens.add({ targets: loser, x: won ? 292 : 28, angle: 80, alpha: 0.4, y: 132, duration: 520 });
  const winner = won ? monsterC : enemyC;
  if (winner) {
    S().tweens.add({ targets: winner, x: won ? 28 : 292, duration: 420 });
    S().tweens.add({ targets: winner, y: (winner.y ?? 120) - 8, duration: 260, yoyo: true, repeat: 3 });
  }

  audio.sfx(won ? 'zone_clear' : 'death_stinger', 0.7);
  S().time.delayedCall(700, () => {
    const panel = S().add.rectangle(GAME_W / 2, 96, 212, 76, PALETTE.ink).setDepth(60).setStrokeStyle(1, won ? PALETTE.gold : PALETTE.steel);
    layer?.add(panel);
    const head = centerText(S(), GAME_W / 2, 76, won ? 'FROGSTER CHAMPION!' : 'FROGSTER DEFEATED!', won ? PALETTE.gold : PALETTE.fog, 16).setDepth(61);
    layer?.add(head);
    S().tweens.add({ targets: head, scaleX: 1.08, scaleY: 1.08, duration: 300, yoyo: true, repeat: won ? 3 : 0 });

    if (won) {
      // The reward ANIMATION.  The tokens themselves are the shell's business
      // and arrive when `finish` calls `api.win`, once.
      const gain = centerText(S(), GAME_W / 2, 100, '+30 TOKENS', PALETTE.gold, 16).setDepth(61);
      layer?.add(gain);
      S().tweens.add({ targets: gain, y: 94, duration: 420, yoyo: true, repeat: -1 });
      audio.sfx('cha_ching', 0.6);
      layer?.add(centerText(S(), GAME_W / 2, 118, `BALANCE AFTER: ${apiRef!.balance() + 30}`, PALETTE.ash).setDepth(61));
    } else {
      layer?.add(centerText(S(), GAME_W / 2, 100, 'NO REWARD. NO REFUND.', PALETTE.ash).setDepth(61));
      layer?.add(centerText(S(), GAME_W / 2, 118, `BALANCE: ${apiRef!.balance()}`, PALETTE.ash).setDepth(61));
    }
    armBtns.push(
      button(S(), GAME_W / 2, 148, 'BACK TO THE ARCADE', () => finish(won), {
        width: 150,
        height: 16,
        fill: won ? PALETTE.tealDark : PALETTE.slate,
      }),
    );
  });
}

/**
 * Say which way it went, once and once only.
 *
 * `ended` latches before anything else happens, so a double-tapped button, a
 * tween that fires twice and a player who finds a second route all end up
 * reporting the same single result -- and the shell's own latch is behind
 * this one, which is two locks on the only door the thirty tokens come out of.
 */
function finish(won: boolean): void {
  if (ended) return;
  ended = true;
  for (const b of armBtns) b.destroy();
  armBtns = [];
  if (won) apiRef!.win();
  else apiRef!.lose();
}

