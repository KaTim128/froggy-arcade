/**
 * The game's font.  PRD AR-2.
 *
 * The canvas backing store really is 320x180 — the 4x you see is a CSS upscale
 * with image-rendering: pixelated.  So a browser-rasterised 8px font gets its
 * antialiasing baked into the buffer, and every soft grey edge pixel is then
 * blown up into a 4x4 grey block.  That is why the old text read as mud.
 *
 * A glyph here is 1-bit: a pixel is on or it is off, authored at exactly the
 * resolution it renders at.  Nothing to blur.
 *
 * Glyphs are authored 5 wide x 8 tall:
 *   rows 0-5   caps, digits and ascenders
 *   rows 2-5   x-height
 *   row 5      baseline (glyphs sit ON it)
 *   rows 6-7   descenders
 *
 * The atlas cell is 6 wide, though — the gap between letters is the blank sixth
 * column, not BitmapText's letterSpacing. Phaser's word wrap measures glyph
 * advances and ignores letterSpacing, so spacing added that way makes every
 * wrapped line overrun its max width by a fifth.
 */

