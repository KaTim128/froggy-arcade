/**
 * Anything with no glyph renders as a hollow box rather than vanishing, so a
 * missing character is visible instead of silently eating text.
 */
const NOTDEF = '...../#####/#...#/#...#/#...#/#####/...../.....';

/** Every character the font can draw, in atlas order. */
export const FONT_CHARS = Object.keys(GLYPHS).join('');

export function hasGlyph(ch: string): boolean {
  return ch in GLYPHS;
}

const CHARS_PER_ROW = 16;

function buildAtlas(): HTMLCanvasElement {
  const chars = [...FONT_CHARS];
  const rows = Math.ceil(chars.length / CHARS_PER_ROW);
  const canvas = document.createElement('canvas');
  canvas.width = CHARS_PER_ROW * FONT_ADVANCE;
  canvas.height = rows * FONT_H;
  const ctx = canvas.getContext('2d')!;

  // White glyphs: BitmapText tints them to the colour the caller asked for.
  ctx.fillStyle = '#ffffff';
  chars.forEach((ch, i) => {
    const ox = (i % CHARS_PER_ROW) * FONT_ADVANCE;
    const oy = Math.floor(i / CHARS_PER_ROW) * FONT_H;
    const rowsOf = (GLYPHS[ch] ?? NOTDEF).split('/');
    for (let y = 0; y < FONT_H; y++) {
      const row = rowsOf[y] ?? '.....';
      for (let x = 0; x < GLYPH_W; x++) {
        if (row[x] === '#') ctx.fillRect(ox + x, oy + y, 1, 1);
      }
    }
  });

  return canvas;
}

/**
 * Register the font once per game.  Lazy rather than done in Boot so that a
 * deep link straight into any scene still gets a font.
 */
export function ensurePixelFont(scene: Phaser.Scene): void {
  if (scene.cache.bitmapFont.has(FONT_KEY)) return;

  if (!scene.textures.exists(TEXTURE_KEY)) {
    scene.textures.addCanvas(TEXTURE_KEY, buildAtlas());
  }

  const data = Phaser.GameObjects.RetroFont.Parse(scene, {
    image: TEXTURE_KEY,
    width: FONT_ADVANCE,
    height: FONT_H,
    chars: FONT_CHARS,
    charsPerRow: CHARS_PER_ROW,
    'offset.x': 0,
    'offset.y': 0,
    'spacing.x': 0,
    'spacing.y': 0,
    lineSpacing: FONT_LINE_H - FONT_H,
  });

  scene.cache.bitmapFont.add(FONT_KEY, data);
}
