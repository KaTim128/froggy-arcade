import { defineConfig, type Plugin } from 'vite';
import { readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { createHash } from 'node:crypto';

/**
 * PLAYS WITH NO INTERNET (user, 1 Nov).  After the build, every file the game
 * is made of -- the page, the code, the sounds, the icons -- is listed in a
 * service worker (dist/sw.js).  The first visit saves them all on the device;
 * from then on the game opens and plays from that copy, wifi or not, and a
 * new version is fetched quietly in the background the next time there is a
 * connection.
 */
function offline(): Plugin {
  let outDir = 'dist';
  return {
    name: 'froggy-offline',
    apply: 'build',
    configResolved(c) {
      outDir = c.build.outDir;
    },
    closeBundle() {
      const files: string[] = [];
      const walk = (dir: string): void => {
        for (const f of readdirSync(dir)) {
          const p = join(dir, f);
          if (statSync(p).isDirectory()) walk(p);
          else if (f !== 'sw.js') files.push(relative(outDir, p).split('\\').join('/'));
        }
      };
      walk(outDir);
      const hash = createHash('sha1');
      for (const f of files.sort()) hash.update(f + statSync(join(outDir, f)).size);
      const version = hash.digest('hex').slice(0, 12);
      const list = JSON.stringify(['./', ...files]);
      writeFileSync(
        join(outDir, 'sw.js'),
        `// Generated by vite.config.ts (offline): the whole game, saved on the device.
const CACHE = 'froggy-${version}';
const FILES = ${list};
self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('froggy-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});
self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  e.respondWith(
    caches.match(req, { ignoreSearch: true }).then((hit) => {
      if (hit) return hit;
      return fetch(req)
        .then((res) => {
          if (res.ok) {
            const copy = res.clone();
            caches.open(CACHE).then((c) => c.put(req, copy));
          }
          return res;
        })
        .catch(() => (req.mode === 'navigate' ? caches.match('./') : Response.error()));
    }),
  );
});
`,
      );
    },
  };
}

export default defineConfig(({ mode }) => ({
  base: process.env.VERCEL ? '/' : '/froggy-arcade/',

  define: {
    __DEV__: JSON.stringify(mode !== 'production'),
  },

  plugins: [offline()],

  build: {
    target: 'es2022',
    chunkSizeWarningLimit: 1600,
  },

  server: {
    port: 5173,
    open: false,
  },
}));
